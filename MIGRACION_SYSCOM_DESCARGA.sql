CREATE TABLE IF NOT EXISTS cotizador_syscom_descargas (
 usuario_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 fuente_cifrada TEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 estado VARCHAR(20) NOT NULL DEFAULT 'configurado',
 archivo_token CHAR(32) NOT NULL DEFAULT '',
 carga_id BIGINT UNSIGNED NULL,
 bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 offset_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 encabezado TEXT NULL,
 filas INT UNSIGNED NOT NULL DEFAULT 0,
 ultimo_intento BIGINT UNSIGNED NOT NULL DEFAULT 0,
 ultimo_exito BIGINT UNSIGNED NOT NULL DEFAULT 0,
 ultimas_filas INT UNSIGNED NOT NULL DEFAULT 0,
 mensaje VARCHAR(500) NOT NULL DEFAULT '',
 actualizado_en DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cotizador_syscom_descarga_limites (
 fuente_hash CHAR(64) NOT NULL PRIMARY KEY,
 ultimo_intento BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
